// Embeds the sample projects (repo-root projects/<genre>/<song>/<song>.studio, built by
// `pnpm samples`) as lazily loaded modules: src/generated/samples/index.ts lists metadata
// and one dynamic import per song, so the library costs nothing until a sample is opened.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const projectsRoot = join(packageRoot, '../../projects');
const outDir = join(packageRoot, 'src/generated/samples');
const GENRES = ['edm', 'rock', 'rap', 'house', 'pop', 'techno'];

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const entries = [];
for (const genre of GENRES) {
  const genreDir = join(projectsRoot, genre);
  if (!existsSync(genreDir)) continue;
  for (const dir of readdirSync(genreDir).sort()) {
    const bundle = join(genreDir, dir, `${dir}.studio`);
    const specPath = join(genreDir, dir, 'song.json');
    if (!existsSync(bundle) || !existsSync(specPath)) continue;
    const spec = JSON.parse(readFileSync(specPath, 'utf8'));
    const id = `${genre}-${dir}`;
    const moduleName = id.replace(/[^a-z0-9-]/g, '');
    writeFileSync(
      join(outDir, `${moduleName}.ts`),
      `// Generated by scripts/codegen.mjs — do not edit.\nexport const bundleBase64 = ${JSON.stringify(readFileSync(bundle).toString('base64'))};\n`,
    );
    entries.push({
      id,
      moduleName,
      genre,
      title: String(spec.title),
      description: typeof spec.description === 'string' ? spec.description : '',
      bpm: Number(spec.bpm),
      bars: Number(spec.bars),
      tracks: Array.isArray(spec.tracks) ? spec.tracks.length : 0,
    });
  }
}

const lines = [
  '// Generated by scripts/codegen.mjs — do not edit.',
  "import type { SampleProject } from '../../features/projects-page/samples';",
  '',
  'export const SAMPLE_PROJECTS: readonly SampleProject[] = [',
  ...entries.map(
    ({ moduleName, ...meta }) =>
      `  { ...${JSON.stringify(meta)}, load: () => import('./${moduleName}').then((m) => m.bundleBase64) },`,
  ),
  '];',
  '',
];
writeFileSync(join(outDir, 'index.ts'), lines.join('\n'));
process.stdout.write(`samples: embedded ${entries.length} sample projects\n`);
