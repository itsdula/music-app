// Bundles Worker/AudioWorklet entry points into self-contained source strings so that any
// host (Next.js/Turbopack, Vite, Electron) can load them from Blob URLs without bundler
// configuration or public-path assumptions. See docs/adr/0006-inline-worker-bundles.md.
import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * @param {{ packageRoot: string, entries: Record<string, string>, outFile?: string }} options
 *   entries: exportName -> entry path relative to packageRoot
 */
export async function buildInlineBundles({
  packageRoot,
  entries,
  outFile = 'src/generated/inline-bundles.ts',
}) {
  const lines = [
    '// AUTO-GENERATED by scripts/inline-bundles.mjs (`pnpm codegen`). Do not edit.',
    '/* eslint-disable */',
  ];
  for (const [exportName, entry] of Object.entries(entries)) {
    const result = await build({
      entryPoints: [join(packageRoot, entry)],
      bundle: true,
      write: false,
      format: 'iife',
      platform: 'browser',
      target: 'es2022',
      minify: true,
      legalComments: 'none',
      logLevel: 'warning',
    });
    const code = result.outputFiles[0].text;
    lines.push(`export const ${exportName}: string = ${JSON.stringify(code)};`);
  }
  if (Object.keys(entries).length === 0) lines.push('export {};');
  const target = join(packageRoot, outFile);
  mkdirSync(join(target, '..'), { recursive: true });
  writeFileSync(target, lines.join('\n') + '\n');
}
